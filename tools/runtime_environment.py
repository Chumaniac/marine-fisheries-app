"""Offline bounded installed-file checks and explicit dependency preparation."""
import base64
from contextlib import contextmanager
import fcntl
import hashlib
from importlib import metadata
import json
import os
from pathlib import Path
import re
import signal
import stat
import subprocess
import sys
import uuid

MAX_FILES = 20000
MAX_BYTES = 512 * 1024**2


def check_environment(root):
    report = {'schema': 'marine.local-environment/v1', 'ready': False, 'reason': None,
              'lockSha256': None, 'packages': 0, 'filesChecked': 0, 'bytesHashed': 0,
              'networkAccess': False, 'repair': 'Prepare Marine.command'}
    try:
        if sys.version_info[:2] != (3, 12):
            raise ValueError('python_version_mismatch')
        lock = root / 'requirements.local.lock'
        if lock.is_symlink() or lock.stat().st_size > 32768:
            raise ValueError('lock_invalid')
        raw = lock.read_bytes(); report['lockSha256'] = hashlib.sha256(raw).hexdigest()
        expected = {}
        for line in raw.decode().splitlines():
            if not line.strip() or line.startswith('#'):
                continue
            match = re.fullmatch(r'([A-Za-z0-9][A-Za-z0-9._-]*)==([A-Za-z0-9][A-Za-z0-9.+!-]*)', line)
            if not match or match[1].lower() in expected or len(expected) >= 128:
                raise ValueError('lock_invalid')
            expected[match[1].lower()] = match[2]
        if not expected:
            raise ValueError('lock_invalid')
        prefix = Path(sys.prefix).resolve()
        for name, version in expected.items():
            dist = metadata.distribution(name)
            if dist.version != version:
                raise ValueError('installed_version_mismatch')
            entries = dist.files
            if not entries or len(entries) > MAX_FILES:
                raise ValueError('installed_metadata_invalid')
            hashed = 0
            for entry in entries:
                if entry.hash is None:  # RECORD itself and generated bytecode have no supplied hash.
                    continue
                if entry.hash.mode != 'sha256':
                    raise ValueError('installed_metadata_invalid')
                path = Path(dist.locate_file(entry))
                if path.is_symlink() or not path.resolve().is_relative_to(prefix):
                    raise ValueError('installed_file_invalid')
                before = path.stat()
                report['filesChecked'] += 1; report['bytesHashed'] += before.st_size
                if (not stat.S_ISREG(before.st_mode) or report['filesChecked'] > MAX_FILES
                        or report['bytesHashed'] > MAX_BYTES):
                    raise ValueError('inspection_capacity')
                with path.open('rb') as stream:
                    actual = base64.urlsafe_b64encode(hashlib.file_digest(stream, 'sha256').digest()).rstrip(b'=').decode()
                after = path.stat()
                if actual != entry.hash.value or (before.st_ino,before.st_size,before.st_mtime_ns) != (after.st_ino,after.st_size,after.st_mtime_ns):
                    raise ValueError('installed_file_mismatch')
                hashed += 1
            if not hashed:
                raise ValueError('installed_metadata_invalid')
            report['packages'] += 1
        report['ready'] = True
    except metadata.PackageNotFoundError:
        report['reason'] = 'installed_package_missing'
    except (OSError, ValueError, UnicodeError):
        reason = str(sys.exception())
        known = {'python_version_mismatch','lock_invalid','installed_version_mismatch','installed_metadata_invalid',
                 'installed_file_invalid','installed_file_mismatch','inspection_capacity'}
        report['reason'] = reason if reason in known else 'environment_unavailable'
    return report


@contextmanager
def environment_lock(root, *, exclusive=False):
    path = root / '.marine-runtime.lock'
    fd = os.open(path, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    try:
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or info.st_nlink != 1 or info.st_size or info.st_mode & 0o077:
            raise ValueError('ENVIRONMENT_LOCK_INVALID')
        try:
            fcntl.flock(fd, (fcntl.LOCK_EX if exclusive else fcntl.LOCK_SH) | fcntl.LOCK_NB)
        except BlockingIOError:
            raise ValueError('ENVIRONMENT_IN_USE; stop this installation before preparation') from None
        yield
    finally:
        os.close(fd)


def run_owned(args, root, **kwargs):
    child = subprocess.Popen(args, cwd=root, **kwargs)
    try:
        stdout, _ = child.communicate()
        return child.returncode, stdout
    finally:
        if child.poll() is None:
            child.terminate()
            try:
                child.wait(timeout=5)
            except subprocess.TimeoutExpired:
                child.kill(); child.wait()


def retained_capacity(root):
    # Preserve every previous/failed environment. Stop before another whole copy
    # would exceed this local allowance; cleanup requires an explicit selection.
    directories = []
    with os.scandir(root) as entries:
        for entry in entries:
            if entry.name.startswith(('.venv.previous-', '.venv.failed-')):
                if entry.is_symlink() or not entry.is_dir(follow_symlinks=False):
                    raise ValueError('ENVIRONMENT_RETENTION_INVALID')
                directories.append(Path(entry.path))
                if len(directories) >= 4:
                    raise ValueError('ENVIRONMENT_RETENTION_CAPACITY')
    used = 0; files = 0
    for directory in [*directories, root/'.venv']:
        if not directory.exists():
            continue
        for folder, dirs, names in os.walk(directory, followlinks=False):
            files += len(dirs) + len(names)
            if files > 80000:
                raise ValueError('ENVIRONMENT_RETENTION_CAPACITY')
            for name in names:
                info = (Path(folder)/name).lstat()
                if stat.S_ISREG(info.st_mode):
                    used += info.st_size
                    if used > 2 * 1024**3:
                        raise ValueError('ENVIRONMENT_RETENTION_CAPACITY')


def prepare(root, uv):
    # Bootstrap Python is outside .venv, so an incorrect interpreter can be repaired.
    from start_app import verify_distribution
    verify_distribution(root)
    with environment_lock(root, exclusive=True):
        environment = root / '.venv'
        if environment.is_symlink() or environment.exists() and not environment.is_dir():
            raise ValueError('ENVIRONMENT_LINK_INVALID')
        retained_capacity(root)
        import shutil
        if shutil.disk_usage(root).free < MAX_BYTES + 64 * 1024**2:
            raise ValueError('ENVIRONMENT_FREE_SPACE_REQUIRED')
        marker = root / '.marine-preparing.json'
        identity = uuid.uuid4().hex
        previous = root / ('.venv.previous-' + identity)
        failed = root / ('.venv.failed-' + identity)
        fd = os.open(marker, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        with os.fdopen(fd, 'w') as stream:
            json.dump({'schema':'marine.environment-preparation/v1','id':identity,
                       'previous':previous.name,'failed':failed.name}, stream)
            stream.flush(); os.fsync(stream.fileno())
        saved = False; attempting = False; success = False
        try:
            if environment.exists():
                environment.rename(previous); saved = True
            attempting = True
            code, _ = run_owned([uv,'venv','--python',sys.executable,str(environment)], root)
            if code:
                return code
            interpreter = str(environment/'bin/python')
            code, _ = run_owned([uv,'pip','sync','--python',interpreter,
                                 str(root/'requirements.local.lock')], root)
            if code:
                return code
            code, raw = run_owned([interpreter,str(root/'tools/runtime_environment.py'),'--check'],
                                  root, stdout=subprocess.PIPE, text=True)
            report = json.loads(raw)
            print(json.dumps(report))
            success = code == 0 and report.get('ready') is True
            return 0 if success else 2
        finally:
            if not success:
                if attempting and environment.exists():
                    environment.rename(failed)
                if saved:
                    previous.rename(environment)
            # SIGKILL leaves this marker: subsequent preparation refuses instead of
            # guessing whether an installer is still running or discarding backups.
            marker.unlink()


if __name__ == '__main__':
    def interrupt(_signal, _frame):
        raise KeyboardInterrupt
    signal.signal(signal.SIGTERM, interrupt)
    try:
        root = Path(__file__).resolve().parents[1]
        if sys.argv[1:] == ['--check']:
            report = check_environment(root); print(json.dumps(report))
            raise SystemExit(0 if report['ready'] else 2)
        if len(sys.argv) != 3 or sys.argv[1] != '--prepare':
            raise ValueError('EXPLICIT_PREPARATION_REQUIRED')
        raise SystemExit(prepare(root, sys.argv[2]))
    except KeyboardInterrupt:
        raise SystemExit(130) from None
    except (OSError, ValueError):
        raise SystemExit('LOCAL_ENVIRONMENT_PREPARATION_REFUSED; stop this installation and check its distribution before retrying') from None
